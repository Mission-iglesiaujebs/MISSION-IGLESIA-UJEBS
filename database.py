"""Storage connection for local SQLite and managed PostgreSQL."""
import os
import sqlite3

DATABASE_URL = os.environ.get("DATABASE_URL", "")

if DATABASE_URL:
    import psycopg
    from psycopg.rows import dict_row

    DatabaseError = psycopg.Error
    IntegrityError = psycopg.IntegrityError
else:
    DatabaseError = sqlite3.Error
    IntegrityError = sqlite3.IntegrityError


class PostgresConnection:
    def __init__(self):
        self.connection = psycopg.connect(DATABASE_URL, row_factory=dict_row)

    def execute(self, sql, parameters=()):
        # Internal statements use qmark placeholders, never user-supplied SQL.
        return self.connection.execute(sql.replace("?", "%s"), parameters)

    def __enter__(self):
        self.transaction = self.connection.transaction()
        self.transaction.__enter__()
        return self

    def __exit__(self, *error):
        return self.transaction.__exit__(*error)

    def close(self):
        self.connection.close()


def open_connection(sqlite_path):
    if DATABASE_URL:
        return PostgresConnection()
    db = sqlite3.connect(sqlite_path)
    db.execute("PRAGMA foreign_keys=ON")
    db.row_factory = sqlite3.Row
    return db


def initialize_schema(db, schema):
    if DATABASE_URL:
        schema = schema.replace("INTEGER PRIMARY KEY,", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
        schema = schema.replace(" BLOB ", " BYTEA ")
    for statement in schema.split(";"):
        if statement.strip():
            db.execute(statement)
